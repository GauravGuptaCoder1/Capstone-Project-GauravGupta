# Task 1 — Load and inspect
# Load the three CSVs with pd.read_csv. orders.shape must print (180, 9) before any cleaning.

BASE_DIR = Path(__file__).resolve().parents[1]

orders = pd.read_csv(BASE_DIR / "data/orders.csv")
