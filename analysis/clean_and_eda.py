# Task 9 — Correlation analysis
# Compute the correlation matrix across rating, returned, discount_pct, quantity. State explicitly which taught correlation-strength band (negligible / weak / moderate / strong, using the 0–0.19 / 0.2–0.39 / 0.4–0.69 / 0.7–1.0 bands) every pairwise value falls into. All six pairs must be labeled negligible (|r| < 0.2) — in particular, label the hypothesis "higher discounts reduce returns" Busted (discount_pct vs returned correlation ≈ -0.09).

corr_cols = ["rating", "returned", "discount_pct", "quantity"]
corr_matrix = orders_merged[corr_cols].corr()

print("Correlation matrix:")
print(corr_matrix.round(3))

def correlation_band(r):
    abs_r = abs(r)
    if abs_r < 0.2:
        return "negligible"
    elif abs_r < 0.4:
        return "weak"
    elif abs_r < 0.7:
        return "moderate"
    else:
        return "strong"

print("\nPairwise correlation strength labels:")

for i in range(len(corr_cols)):
    for j in range(i + 1, len(corr_cols)):
        col1 = corr_cols[i]
        col2 = corr_cols[j]
        r = corr_matrix.loc[col1, col2]
        print(f"{col1} vs {col2}: r = {r:.3f}, strength = {correlation_band(r)}")

discount_return_corr = corr_matrix.loc["discount_pct", "returned"]

hypothesis_result = (
    "Confirmed"
    if discount_return_corr <= -0.2
    else "Busted"
)

print(
    "\nHypothesis: higher discounts reduce returns:",
    hypothesis_result,
    f"(discount_pct vs returned correlation = {discount_return_corr:.3f})"
)

# Task 10 — Outlier-corrected time series
